use anyhow::{Context, Result, bail, ensure};
use mcpmem::{ServiceAction, Transport, config::Config, config_file, runtime::RuntimeRole};
use std::{
    env, fs,
    io::{ErrorKind, Write},
    path::{Path, PathBuf},
    process::Command,
};

const UNIT: &str = "mcpmem.service";
const MARKER: &str = "# Generated by mcpmem service install\n";

pub(super) fn run(action: ServiceAction) -> Result<()> {
    ensure!(
        cfg!(target_os = "linux"),
        "service management requires Linux with a systemd user manager"
    );
    let directory = env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| {
            env::var_os("HOME")
                .map(PathBuf::from)
                .filter(|p| p.is_absolute())
                .map(|p| p.join(".config"))
        })
        .context("cannot locate the user configuration directory (XDG_CONFIG_HOME or HOME)")?
        .join("systemd/user");
    let unit = match action {
        ServiceAction::Install { config } => Some(configured_unit(config)?),
        ServiceAction::Uninstall => None,
        ServiceAction::Status => return status(&directory.join(UNIT)),
    };
    manage(&directory, unit.as_deref(), |args| {
        let status = Command::new("systemctl")
            .arg("--user")
            .args(args)
            .status()
            .context("cannot execute systemctl --user")?;
        ensure!(
            status.success(),
            "systemctl --user {} failed ({status})",
            args.join(" ")
        );
        Ok(())
    })?;
    println!(
        "{} {UNIT}",
        if unit.is_some() {
            "Installed"
        } else {
            "Uninstalled"
        }
    );
    Ok(())
}

fn configured_unit(config: Option<PathBuf>) -> Result<String> {
    let config = config
        .or_else(|| {
            env::var_os(config_file::CONFIG_PATH_ENV)
                .filter(|s| !s.is_empty())
                .map(PathBuf::from)
        })
        .context("service install requires --config PATH or MCP_MEMORY_CONFIG")?;
    let cwd = env::current_dir()?;
    let config = cwd.join(config);
    ensure!(
        config.to_str().is_some(),
        "the server requires a UTF-8 config path"
    );
    let (args, _) = config_file::resolve([
        "mcpmem".into(),
        "--config".into(),
        config.clone().into_os_string(),
    ])?;
    let settings = Config::from_args(&args)?;
    ensure!(
        settings.transport != Transport::Stdio
            || !settings.roles.roles().contains(&RuntimeRole::Mcp),
        "a systemd service has no MCP client on stdin; set [server] transport = \"http\" or select only worker roles"
    );
    render(&env::current_exe()?, &cwd, &config)
}

// ExecStart is parsed by systemd, without a shell. The ':' prefix turns off
// its environment-variable substitution, while '%%' escapes its specifiers.
fn quote(value: &Path) -> Result<String> {
    let s = value.to_str().context("service paths must be UTF-8")?;
    ensure!(
        !s.chars().any(char::is_control),
        "control characters are unsupported in service paths"
    );
    Ok(format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    ))
}

fn render(exe: &Path, cwd: &Path, config: &Path) -> Result<String> {
    // env -C preserves all relative paths in the TOML, including file-backed
    // credentials. Its arguments use the same quoting rules as the executable.
    Ok(format!(
        "{MARKER}[Unit]\nDescription=MCP Memory Server\n\n[Service]\nType=exec\nExecStart=:/usr/bin/env -C {} {} --config {}\nRestart=on-failure\nRestartSec=5s\n\n[Install]\nWantedBy=default.target\n",
        quote(cwd)?,
        quote(exe)?,
        quote(config)?
    ))
}

fn owned_unit(path: &Path) -> Result<Option<String>> {
    match fs::symlink_metadata(path) {
        Ok(meta) => {
            ensure!(
                meta.is_file(),
                "{} is not a regular unit file",
                path.display()
            );
            let contents = fs::read_to_string(path)
                .with_context(|| format!("cannot read {}", path.display()))?;
            ensure!(
                contents.starts_with(MARKER),
                "{} is not managed by mcpmem",
                path.display()
            );
            Ok(Some(contents))
        }
        Err(e) if e.kind() == ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("cannot inspect {}", path.display())),
    }
}

const STATUS_PROPERTIES: &str =
    "LoadState,UnitFileState,ActiveState,SubState,FragmentPath,NeedDaemonReload";

fn status(path: &Path) -> Result<()> {
    ensure!(
        owned_unit(path)?.is_some(),
        "{UNIT} is not installed at {}",
        path.display()
    );
    let output = Command::new("systemctl")
        .args([
            "--user",
            "show",
            "--all",
            "--property",
            STATUS_PROPERTIES,
            UNIT,
        ])
        .output()
        .context("cannot execute systemctl --user show")?;
    let stdout = std::str::from_utf8(&output.stdout)?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let detail = stderr.trim();
        if !detail.is_empty() {
            bail!(
                "systemctl --user show {UNIT} failed ({}): {detail}",
                output.status
            );
        }
        // A missing unit can return nonzero with LoadState only on stdout.
        if let Some(load) = stdout
            .lines()
            .find_map(|line| line.strip_prefix("LoadState="))
        {
            bail!(
                "systemctl --user show {UNIT} failed ({}), LoadState={load}",
                output.status
            );
        }
        bail!("systemctl --user show {UNIT} failed ({})", output.status);
    }
    check_status(path, stdout)?;
    println!(
        "{UNIT} is installed, enabled and running ({})",
        path.display()
    );
    Ok(())
}

fn check_status(path: &Path, output: &str) -> Result<()> {
    let properties: std::collections::HashMap<_, _> = output
        .lines()
        .filter_map(|line| line.split_once('='))
        .collect();
    let property = |name: &str| {
        properties
            .get(name)
            .copied()
            .with_context(|| format!("systemctl omitted {name} for {UNIT}"))
    };
    let load = property("LoadState")?;
    ensure!(
        load == "loaded",
        "{UNIT} has LoadState={load} (expected loaded)"
    );
    let fragment = Path::new(property("FragmentPath")?);
    if fragment != path {
        // The user's configuration directory can itself be a symlink.
        let resolved = (fragment.canonicalize(), path.canonicalize());
        ensure!(
            matches!(resolved, (Ok(actual), Ok(expected)) if actual == expected),
            "systemd loaded {UNIT} from {} (expected {})",
            fragment.display(),
            path.display()
        );
    }
    let enabled = property("UnitFileState")?;
    let active = property("ActiveState")?;
    let sub = property("SubState")?;
    let reload = property("NeedDaemonReload")?;
    ensure!(
        (enabled, active, sub, reload) == ("enabled", "active", "running", "no"),
        "{UNIT}: UnitFileState={enabled}, ActiveState={active}, SubState={sub}, NeedDaemonReload={reload} (expected enabled, active, running, no)"
    );
    Ok(())
}

fn manage(
    directory: &Path,
    desired: Option<&str>,
    mut systemctl: impl FnMut(&[&str]) -> Result<()>,
) -> Result<()> {
    if desired.is_some() {
        fs::create_dir_all(directory)?;
    }
    let lock = match fs::File::open(directory) {
        Err(e) if desired.is_none() && e.kind() == ErrorKind::NotFound => return Ok(()),
        result => result?,
    };
    lock.lock().context("locking systemd user unit directory")?;
    let path = directory.join(UNIT);
    let current = owned_unit(&path)?;
    match desired {
        Some(contents) => {
            if current.as_deref() != Some(contents) {
                let mut file = tempfile::NamedTempFile::new_in(directory)?;
                file.write_all(contents.as_bytes())?;
                file.persist(&path)?;
            }
            systemctl(&["daemon-reload"])?;
            systemctl(&["enable", UNIT])?;
            systemctl(&["restart", UNIT])
        }
        None => {
            if current.is_some() {
                systemctl(&["disable", "--now", UNIT])?;
                fs::remove_file(&path)?;
            }
            // Also finish a retry after removal succeeded but reload failed.
            systemctl(&["daemon-reload"])
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn status_requires_the_expected_unit_and_all_healthy_properties() {
        let path = Path::new("/tmp/some=user/mcpmem.service");
        let healthy = "SubState=running\nFragmentPath=/tmp/some=user/mcpmem.service\nActiveState=active\nNeedDaemonReload=no\nLoadState=loaded\nUnitFileState=enabled\n";
        check_status(path, healthy).unwrap();
        for (good, bad) in [
            ("UnitFileState=enabled", "UnitFileState=disabled"),
            ("UnitFileState=enabled", "UnitFileState=enabled-runtime"),
            ("ActiveState=active", "ActiveState=failed"),
            ("SubState=running", "SubState=exited"),
            ("LoadState=loaded", "LoadState=not-found"),
            ("NeedDaemonReload=no", "NeedDaemonReload=yes"),
            ("/tmp/some=user/mcpmem.service", "/other/mcpmem.service"),
        ] {
            let error = check_status(path, &healthy.replace(good, bad)).unwrap_err();
            assert!(error.to_string().contains(bad), "{error}");
        }
        let error = check_status(path, &healthy.replace("NeedDaemonReload=no", "")).unwrap_err();
        assert!(error.to_string().contains("omitted NeedDaemonReload"));
    }

    #[test]
    fn unit_keeps_paths_literal() {
        let unit = render(
            Path::new("/opt/MCP Memory/mcpmem"),
            Path::new("/home/a/100%/$USER"),
            Path::new("/home/a/a\"b\\c.toml"),
        )
        .unwrap();
        assert!(unit.contains(r#"ExecStart=:/usr/bin/env -C "/home/a/100%%/$USER" "/opt/MCP Memory/mcpmem" --config "/home/a/a\"b\\c.toml""#));
        assert!(unit.contains("WantedBy=default.target"));
        assert!(quote(Path::new("x\ny")).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn install_and_uninstall_are_retryable() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("systemd/user");
        let path = dir.join(UNIT);
        let unit = format!("{MARKER}[Unit]\n");
        let mut calls = Vec::new();
        let mut record = |args: &[&str]| {
            calls.push(args.join(" "));
            Ok(())
        };
        manage(&dir, Some(&unit), &mut record).unwrap();
        manage(&dir, Some(&unit), &mut record).unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), unit);
        assert_eq!(
            calls,
            [
                "daemon-reload",
                "enable mcpmem.service",
                "restart mcpmem.service"
            ]
            .repeat(2)
        );

        let failure = manage(&dir, None, |_| anyhow::bail!("manager unavailable"));
        assert!(failure.is_err());
        assert!(path.exists());
        let mut removal = Vec::new();
        let mut record = |args: &[&str]| {
            removal.push(args.join(" "));
            Ok(())
        };
        manage(&dir, None, &mut record).unwrap();
        manage(&dir, None, &mut record).unwrap();
        assert_eq!(
            removal,
            [
                "disable --now mcpmem.service",
                "daemon-reload",
                "daemon-reload"
            ]
        );
        assert!(!path.exists());
    }

    #[cfg(unix)]
    #[test]
    fn foreign_files_and_symlinks_are_preserved() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join(UNIT);
        fs::write(&path, "custom").unwrap();
        for action in [Some(MARKER), None] {
            assert!(manage(tmp.path(), action, |_| panic!("manager called")).is_err());
        }
        assert_eq!(fs::read_to_string(&path).unwrap(), "custom");
        fs::remove_file(&path).unwrap();
        std::os::unix::fs::symlink(tmp.path().join("missing"), &path).unwrap();
        for action in [Some(MARKER), None] {
            assert!(manage(tmp.path(), action, |_| panic!("manager called")).is_err());
        }
        assert!(path.is_symlink());
    }
}
